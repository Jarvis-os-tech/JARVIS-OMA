"""Derive the QML consumer contract from the canonical JSON Schema."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]


def generated():
    schema = json.loads((ROOT / 'contracts/task-event-v1.json').read_text())
    return '.pragma library\n// Generated by scripts/generate_task_event_contract.py; do not edit.\nvar contract = ' + json.dumps(schema, ensure_ascii=False, separators=(',', ':')) + ';\n'


if __name__ == '__main__':
    (ROOT / 'ui/jarvis_widgets/TaskEventContract.js').write_text(generated())
